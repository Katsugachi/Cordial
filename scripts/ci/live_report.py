#!/usr/bin/env python3
"""Turn the live model test output into a readable transcript.

The behaviour suite prints each prompt, the stop reason and the model's answer.
CI cannot rely on job logs being downloadable, so this script writes the same
record into the repository, where a reviewer can read it next to the prompt.

Usage: live_report.py <test-output-log> <output.md>
"""

from __future__ import annotations

import datetime as dt
import os
import re
import sys

SECTION = re.compile(r"^--- (?P<prompt>.+)$")
META = re.compile(r"^\((?P<stop>[A-Za-z_]+)(?:, (?P<words>\d+) words)?\)$")
RESULT = re.compile(r"^\s*test\s+(?P<name>\S+)\s+\.\.\.\s+(?P<status>ok|FAILED|ignored)")


def parse(log: str) -> tuple[list[dict[str, str]], list[tuple[str, str]]]:
    sections: list[dict[str, str]] = []
    results: list[tuple[str, str]] = []
    current: dict[str, str] | None = None
    body: list[str] = []
    meta: str | None = None

    for line in log.splitlines():
        match = SECTION.match(line)
        if match:
            current = {"prompt": match.group("prompt").strip()}
            body = []
            meta = None
            continue
        if current is not None:
            if line.strip() == "---":
                if meta:
                    current["meta"] = meta
                current["answer"] = "\n".join(body).strip()
                sections.append(current)
                current = None
                body = []
                meta = None
                continue
            meta_match = META.match(line.strip())
            if meta_match and not body:
                words = meta_match.group("words")
                stop = meta_match.group("stop").lower()
                meta = stop + (f" · {words} words" if words else "")
                continue
            body.append(line)
        else:
            result = RESULT.match(line)
            if result:
                results.append((result.group("name"), result.group("status")))
    return sections, results


def render(sections: list[dict[str, str]], results: list[tuple[str, str]]) -> str:
    today = dt.date.today().isoformat()
    runner = os.environ.get("GITHUB_SERVER_URL", "https://github.com")
    run_id = os.environ.get("GITHUB_RUN_ID", "")
    repo = os.environ.get("GITHUB_REPOSITORY", "Katsugachi/Cordial")

    lines = [
        "# Live model transcript",
        "",
        "Generated by `crates/cordial-core/tests/live_model.rs` on every live run:",
        "the same prompts the harness sends in the app, answered by the real",
        "LFM3-VL-2B Q4_K_M weights on CPU. Regenerate with `make live`.",
        "",
        f"- Date: {today}",
        f"- Build: [{run_id}]({runner}/{repo}/actions/runs/{run_id})" if run_id else "- Build: local",
        "",
    ]

    passed = sum(1 for _, status in results if status == "ok")
    failed = [name for name, status in results if status == "FAILED"]
    lines.append(f"- Assertions: {passed} passed, {len(failed)} failed")
    if failed:
        lines.append("")
        lines.append("Failures: " + ", ".join(f"`{name}`" for name in failed))
    lines.append("")

    for index, section in enumerate(sections, start=1):
        lines.append(f"## {index}. {section['prompt']}")
        lines.append("")
        if section.get("meta"):
            lines.append(f"*{section['meta']}*")
            lines.append("")
        answer = section.get("answer") or "_(no answer)_"
        for line in answer.splitlines():
            lines.append(f"> {line}" if line.strip() else ">")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    log_path, out_path = sys.argv[1], sys.argv[2]
    try:
        with open(log_path, "r", encoding="utf-8", errors="replace") as handle:
            log = handle.read()
    except FileNotFoundError:
        print(f"no test output at {log_path}")
        return 1

    sections, results = parse(log)
    if not sections:
        print("no finished question/answer sections found in the log")
        return 1

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(render(sections, results))
    print(f"wrote {out_path} ({len(sections)} answers)")
    return 0 if not any(status == "FAILED" for _, status in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
